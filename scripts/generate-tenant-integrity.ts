import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { buildIntegrity } from "./tenant-integrity-model";
const result = buildIntegrity(readFileSync("prisma/schema.prisma", "utf8"));
const directory = "prisma/migrations/20261028000000_enforce_tenant_integrity";
if (!process.argv.includes("--metadata-only")) {
mkdirSync(directory, { recursive: true });
if (existsSync(`${directory}/migration.sql`) && readFileSync(`${directory}/migration.sql`, "utf8") !== result.sql) {
  throw new Error("Existing integrity migration differs. Add a new migration version instead of rewriting applied history.");
}
writeFileSync(`${directory}/migration.sql`, result.sql);
}
writeFileSync("src/lib/db/tenant-model-metadata.ts", "// Generated by scripts/generate-tenant-integrity.ts.\nexport const TENANT_MODEL_METADATA = " + JSON.stringify(result.metadata, null, 2) + " as const;\n");
console.log(`Generated ${result.rules.length} relation checks and scope guards for ${Object.keys(result.immutable).length} models.`);
